  text         text NOT NULL,
  created_at   timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_comments_entity ON comments (entity_type, entity_id, created_at);

-- 031 / 033: the author must approve each step. One row per (record, stage).
CREATE TABLE IF NOT EXISTS author_approvals (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type         text NOT NULL CHECK (entity_type IN ('ordinance', 'resolution')),
  entity_id           bigint NOT NULL,
  stage               text NOT NULL
                      CONSTRAINT author_approvals_stage_check

-- =============================================================================
-- SB Office System — full database schema
-- =============================================================================
--
-- Builds the whole database from nothing, in one run, on an EMPTY Supabase
-- project. Use it to set up a new client / environment.
--
--   1. Create a new Supabase project.
--   2. SQL Editor -> paste this file -> Run.
--   3. Run seed_first_admin.sql (edit the name/username/email/password first).
--   4. Point the backend's .env (SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY) at
--      the new project.
--
-- This file is the end result of migrations 001-036 plus the tables that were
-- originally created by hand in the Supabase dashboard. Do NOT run the
-- numbered migrations on a database built from this file — they are already
-- included. The numbered files stay as the change history for the existing
-- production database.
--
-- Keeping it current: every new numbered migration must also be reflected
-- here (edit the CREATE TABLE / function directly), so a fresh install always
-- matches production.
--
-- Not included on purpose (exist in the original production database but are
-- unused by the app):
--   * notifications table   — meant to be dropped by 017
--   * reactions table       — no code reads or writes it
--   * auto_end_terms()      — replaced by autoEndTerms() in the backend
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- Accounts
-- -----------------------------------------------------------------------------

-- role 'admin' = office staff (secretary, clerk)
-- role 'user'  = Sangguniang members (councilor, vice_mayor, liga, sk)
-- See helpers/roles.js (ROLE_POSITIONS).
CREATE TABLE IF NOT EXISTS users (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                  varchar NOT NULL,
  username              varchar NOT NULL UNIQUE,
  email                 varchar UNIQUE,
  password              varchar NOT NULL,                 -- bcrypt hash
  role                  text NOT NULL DEFAULT 'user'
                        CONSTRAINT users_role_check CHECK (role IN ('admin', 'user')),
  position              text
                        CONSTRAINT users_position_check CHECK (position IN (
                          'secretary', 'clerk',
                          'councilor', 'vice_mayor', 'liga_ng_mga_barangay', 'sk_federated'
                        )),
  photo                 text,                             -- public URL
  photo_path            text,                             -- path in the 'assets' bucket
  is_archived           boolean DEFAULT false,
  archived_at           timestamptz,
  archived_by           bigint REFERENCES users(id),
  must_change_password  boolean NOT NULL DEFAULT false,   -- 012
  email_notifications   boolean NOT NULL DEFAULT true,    -- 015
  reset_token           text,                             -- 022
  reset_token_expires   timestamptz,                      -- 022
  tour_completed        boolean NOT NULL DEFAULT false,   -- 036
  created_at            timestamptz NOT NULL DEFAULT now()
);

-- 011: "JDoe" and "jdoe" can't both exist.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_ci ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_ci    ON users (lower(email));
-- 022: two live reset links can never collide.
CREATE UNIQUE INDEX IF NOT EXISTS users_reset_token_idx
  ON users (reset_token) WHERE reset_token IS NOT NULL;

-- -----------------------------------------------------------------------------
-- Councils and council members
-- -----------------------------------------------------------------------------

-- 001: one row per Sangguniang Bayan term (e.g. "2022-2025").
CREATE TABLE IF NOT EXISTS councils (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term_label  text NOT NULL UNIQUE,
  -- 037: 12 = "12th Sangguniang Bayan"; NULL = not set, term shown instead.
  council_number  integer CHECK (council_number BETWEEN 1 AND 999),
  term_start  date,
  term_end    date,
  status      text NOT NULL DEFAULT 'concluded'
              CHECK (status IN ('upcoming', 'active', 'concluded')),
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS councils_council_number_unique
  ON councils (council_number) WHERE council_number IS NOT NULL;

-- A person who sits (or sat) on the council. Position lives on the term, not
-- here, because it can change between terms (002, 006).
CREATE TABLE IF NOT EXISTS sb_council_members (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name    text NOT NULL,
  photo        text,
  photo_path   text,
  is_archived  boolean DEFAULT false,
  archived_at  timestamptz,
  archived_by  bigint REFERENCES users(id),
  -- 031: the login account this member signs in with (one-to-one, optional).
  user_id      bigint REFERENCES users(id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS sb_council_members_user_id_unique
  ON sb_council_members (user_id) WHERE user_id IS NOT NULL;

-- One row per member per council they served in.
CREATE TABLE IF NOT EXISTS sb_council_member_terms (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  council_member_id  bigint NOT NULL REFERENCES sb_council_members(id),
  council_id         bigint REFERENCES councils(id),               -- 002
  term_period        text NOT NULL,
  term_start         date NOT NULL,
  term_end           date,
  -- 'Vice Mayor', 'Councilor', 'Liga ng mga Barangay President',
  -- 'SK Federated President'
  position           text,                                         -- 002
  status             text NOT NULL DEFAULT 'active',
  is_reelected       boolean NOT NULL DEFAULT false,
  notes              text,
  display_order      integer,                                      -- 032, NULL = sorted last
  created_at         timestamptz NOT NULL DEFAULT now()
);

-- 005: only one active Vice Mayor / Liga President / SK President per council.
CREATE UNIQUE INDEX IF NOT EXISTS uniq_active_singular_position_per_council
  ON sb_council_member_terms (council_id, position)
  WHERE status = 'active'
    AND position IN ('Vice Mayor', 'Liga ng mga Barangay President', 'SK Federated President');
CREATE INDEX IF NOT EXISTS idx_sb_council_member_terms_council_order
  ON sb_council_member_terms (council_id, display_order);
CREATE INDEX IF NOT EXISTS idx_sb_council_member_terms_member
  ON sb_council_member_terms (council_member_id);

-- -----------------------------------------------------------------------------
-- Legislative records
-- -----------------------------------------------------------------------------
-- Review workflow (helpers/legislativeReviewRoutes.js):
--   pending -> accepted -> first_reading -> second_reading -> third_reading
--           -> ready_to_publish -> approved -> published
--   pending <-> needs_revision,  any reading stage -> rejected

CREATE TABLE IF NOT EXISTS ordinances (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordinance_number          text,
  title                     text NOT NULL,
  year                      integer,
  category                  text,                                  -- 013
  filename                  text NOT NULL,
  filetype                  text NOT NULL,
  filepath                  text NOT NULL,                         -- path in 'assets'
  extracted_text            text,                                  -- PDF text / OCR, used by search
  status                    text NOT NULL DEFAULT 'pending'
                            CONSTRAINT ordinances_status_check CHECK (status IN (
                              'pending', 'needs_revision', 'accepted',
                              'first_reading', 'second_reading', 'third_reading',
                              'ready_to_publish', 'approved', 'published', 'rejected'
                            )),
  revision_count            integer DEFAULT 0,
  reviewed_by               bigint REFERENCES users(id),
  reviewed_at               timestamptz,
  approved_on               timestamptz,                           -- 026, set by VM approval
  author_approval_required  boolean NOT NULL DEFAULT false,        -- 031
  created_by                bigint REFERENCES users(id),           -- 015
  uploaded_at               timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS resolutions (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resolution_number         text,
  title                     text NOT NULL,
  year                      integer,
  category                  text,
  filename                  text NOT NULL,
  filetype                  text NOT NULL,
  filepath                  text NOT NULL,
  extracted_text            text,
  status                    text NOT NULL DEFAULT 'pending'
                            CONSTRAINT resolutions_status_check CHECK (status IN (
                              'pending', 'needs_revision', 'accepted',
                              'first_reading', 'second_reading', 'third_reading',
                              'ready_to_publish', 'approved', 'published', 'rejected'
                            )),
  revision_count            integer DEFAULT 0,
  reviewed_by               bigint REFERENCES users(id),
  reviewed_at               timestamptz,
  approved_on               timestamptz,
  author_approval_required  boolean NOT NULL DEFAULT false,
  created_by                bigint REFERENCES users(id),
  uploaded_at               timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ordinances_status  ON ordinances (status);
CREATE INDEX IF NOT EXISTS idx_resolutions_status ON resolutions (status);


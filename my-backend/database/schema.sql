-- Authors / co-authors / sponsors of a record (004, 021).
-- term_id pins the credit to the membership that was current at the time,
-- so the displayed position never changes later.
CREATE TABLE IF NOT EXISTS ordinance_officials (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordinance_id  bigint NOT NULL REFERENCES ordinances(id),
  official_id   bigint NOT NULL REFERENCES sb_council_members(id),
  term_id       bigint REFERENCES sb_council_member_terms(id) ON DELETE SET NULL,
  role          text NOT NULL DEFAULT 'author'
                CHECK (role IN ('author', 'co_author', 'sponsor'))
);

-- Note: unlike ordinance_officials, production keys this table on
-- (resolution_id, official_id) with no id column. Kept identical here.
CREATE TABLE IF NOT EXISTS resolution_officials (
  resolution_id  bigint NOT NULL REFERENCES resolutions(id),
  official_id    bigint NOT NULL REFERENCES sb_council_members(id),
  term_id        bigint REFERENCES sb_council_member_terms(id) ON DELETE SET NULL,
  role           text NOT NULL DEFAULT 'author'
                 CHECK (role IN ('author', 'co_author', 'sponsor')),
  PRIMARY KEY (resolution_id, official_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ordinance_officials_unique_role
  ON ordinance_officials (ordinance_id, official_id, role);
CREATE UNIQUE INDEX IF NOT EXISTS resolution_officials_unique_role
  ON resolution_officials (resolution_id, official_id, role);

-- Review comments on a record. entity_type/entity_id point at any record
-- type, with no FK, so a record's thread survives archive + restore.
CREATE TABLE IF NOT EXISTS comments (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type  text NOT NULL,
  entity_id    bigint NOT NULL,
